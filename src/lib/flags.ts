// D31 (DF-00C): кабинет подрядчика заморожен до отдельного решения
// владельца. Флаг читается ТОЛЬКО на сервере (proxy.ts, серверные
// компоненты) и передаётся пропсами — сознательно не NEXT_PUBLIC,
// чтобы состояние кабинета не требовало пересборки и не светилось
// в клиентский бандл. Значение читается при каждом обращении: на
// Vercel смена env не требует пересборки.
export function contractorPortalEnabled(): boolean {
  return process.env.CONTRACTOR_PORTAL_ENABLED === 'true'
}
