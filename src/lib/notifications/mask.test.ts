import { describe, it, expect } from 'vitest'
import { maskPII } from './mask'

// ─── DF-04 / RULES 2.4: маскирование телефонов и email в списке ──────
// Карточка DF-04: «тела писем в списке маскируются, полный текст — по
// клику». Полный текст остаётся в API-ответе мастеру — маска чисто
// отображенческая, поэтому проверяем чистую функцию 1-в-1.

describe('DF-04 maskPII: email', () => {
  it('обычный адрес: локальная часть скрыта, домен виден', () => {
    expect(maskPII('Письмо ушло на ivan@mail.ru вчера')).toBe('Письмо ушло на iv***@mail.ru вчера')
  })

  it('короткая локальная часть тоже маскируется', () => {
    expect(maskPII('a@b.ru')).toBe('a***@b.ru')
  })

  it('поддомены и составные адреса не ломаются', () => {
    expect(maskPII('user.name+tag@mx.test.example')).toBe('us***@mx.test.example')
  })

  it('ссылки и текст без адресов не трогаются', () => {
    expect(maskPII('Заявка: http://x.test/client/orders/abc — статус сменился')).toBe(
      'Заявка: http://x.test/client/orders/abc — статус сменился'
    )
  })
})

describe('DF-04 maskPII: телефоны', () => {
  it('формат +7 с разделителями: страна и последние две цифры видны', () => {
    expect(maskPII('Телефон +7 999 123-45-67 указан в анкете')).toBe(
      'Телефон +7 *** ***-**-67 указан в анкете'
    )
  })

  it('слитный номер без +: первые две и последние две цифры', () => {
    expect(maskPII('89991234567')).toBe('89*******67')
  })

  it('короткие числа (меньше шести цифр) не считаются телефоном', () => {
    expect(maskPII('Заявка 1-45, вес 12345 кг')).toBe('Заявка 1-45, вес 12345 кг')
  })

  it('email и телефон в одном тексте — маскируются оба', () => {
    const out = maskPII('Клиент ivan@mail.ru, тел. +7 999 123-45-67')
    expect(out).toBe('Клиент iv***@mail.ru, тел. +7 *** ***-**-67')
  })
})
