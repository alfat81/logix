// ─── DF-04: маскирование персональных данных (RULES 2.4) ─────────────
// Карточка DF-04: «тела писем в списке маскируются (RULES 2.4), полный
// текст — по клику». RULES 2.4: «персональные данные маскировать
// телефоны и email» — та же дисциплина, что для логов/Sentry, только
// здесь поверхность — список журнала на экране (плечом к плечу с
// чужими глазами). Полный текст мастер раскрывает осознанным кликом.
//
// Маскирование — по месту использования, не в данных: API отдаёт
// мастеру полный текст (журнал — рабочий инструмент диагностики,
// см. шапку GET /api/admin/notifications), маска применяется в UI
// до клика. Поэтому функция чистая и покрывается unit-тестом 1-в-1.
//
// Правила:
//   email  — первые символы локальной части + ***, домен целиком:
//            «ivan@mail.ru» → «iv***@mail.ru» (домен нужен мастеру
//            для диагностики «на какой адрес не ушло»);
//   телефон — страна/префикс и две последние цифры, середина в *:
//            «+7 999 123-45-67» → «+7 *** ***-**-67».

export function maskPII(text: string): string {
  return text
    .replace(
      /([A-Za-z0-9._%+-]{1,2})[A-Za-z0-9._%+-]*(@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)/g,
      '$1***$2'
    )
    .replace(/\+?\d[\d\s().-]{4,}\d/g, (m) => {
      if ((m.match(/\d/g) ?? []).length < 6) return m
      const headLen = m.startsWith('+') ? 3 : 2
      return m.slice(0, headLen) + m.slice(headLen, -2).replace(/\d/g, '*') + m.slice(-2)
    })
}
