#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Эталоны DF-19: сверка расчётов таможенных платежей с реальными ДТ/ДТС клиента.

Эталон №1: ДТ 10132160/180526/5191269 + ДТС-1 (FCA CHENGDU, авиа, 4 кода FESTO,
USD, курс 73,1275 на 18.05.2026 — дата регистрации ДТ) — сводные числа из
разбора 30.10.2026 (worklog). Перевозка распределена по весу НЕТТО — подтверждено
брокером 30.10.2026 (п. 6.1).

Эталон №2: ДТ 10418010/230126/5008411 + ДТС-1 (FCA ISTANBUL, Турция, авто).
Цена по договору EUR 39 000 (курс 88,7898), счёт-инвойс выставлен в TRY
(1 832 173.21, курс 17,5789 за 10 единиц — номинал котировки ЦБ).

Эталон №3: ДТ 10702070/250326/5113751 (FOB NINGBO, Китай -> DE, море, USD,
курс 80,9604 на 25.03.2026 — дата регистрации). ДТС не приложена: фрахт
восстановлен обратным расчётом (ТС/курс − цена товара).

Сборы — шкала с 01.01.2026 (ПП РФ от 28.11.2024 № 1637, ред. ПП от 23.10.2025
№ 1638); НДС 22% с 01.01.2026 (ФЗ от 28.11.2025 № 425-ФЗ).

Запуск: python3 scripts/verify_df19_examples.py   (exit 1 — есть расхождение)
"""
from decimal import Decimal, ROUND_HALF_UP
import sys

Q = Decimal('0.01')


def r2(x: Decimal) -> Decimal:
    return x.quantize(Q, rounding=ROUND_HALF_UP)


def scale_2026(customs_value: Decimal) -> Decimal:
    """Шкала сборов с 01.01.2026: диапазон ТС (млн ₽) -> сбор, ₽."""
    v = customs_value
    bounds = [
        (Decimal('200000'), Decimal('1231')),
        (Decimal('450000'), Decimal('2462')),
        (Decimal('1200000'), Decimal('4924')),
        (Decimal('2700000'), Decimal('13541')),
        (Decimal('4200000'), Decimal('18465')),
        (Decimal('5500000'), Decimal('21344')),
        (Decimal('10000000'), Decimal('49240')),
    ]
    for upper, fee in bounds:
        if v <= upper:
            return fee
    return Decimal('73860')


CHECKS = []


def check(name: str, expected, actual) -> None:
    ok = Decimal(str(expected)) == Decimal(str(actual))
    CHECKS.append((name, ok, expected, actual))


# ---------- Эталон №1: ДТ 10132160/180526/5191269 (FCA авиа, FESTO) ----------
ts1 = Decimal('671977.28')
duty1 = Decimal('66146.74')
vat1 = r2((ts1 + duty1) * Decimal('0.22'))          # НДС = (ТС + пошлина) x 22%
check('№1 НДС (ТС+пошлина) x 22%', '162387.28', vat1)
check('№1 сбор по шкале (ТС 671 977.28 -> скобка 450–1200 тыс.)', '4924', scale_2026(ts1))
total1 = duty1 + vat1 + scale_2026(ts1)
check('№1 итог платежей (пошлина+НДС+сбор)', '233458.02', total1)
# сбор НЕ входит в базу НДС — иначе копейка уехала бы
check('№1 база НДС без сбора', '738124.02', ts1 + duty1)

# ---------- Эталон №2: ДТ 10418010/230126/5008411 (FCA ISTANBUL) ----------
price2 = r2(Decimal('39000') * Decimal('88.7898'))   # цена по договору EUR x курс
check('№2 цена по курсу (гр. 12 ДТС)', '3462802.20', price2)
ts2 = price2 + Decimal('67532.08')                   # + перевозка (гр. 17 ДТС-1)
check('№2 ТС = гр.12 + гр.20 − гр.24', '3530334.28', ts2)
check('№2 сбор по шкале (скобка 2,7–4,2 млн)', '18465', scale_2026(ts2))
vat2 = r2(ts2 * Decimal('0.22'))                     # пошлины нет (8532230000, 0%)
check('№2 НДС 22% от ТС (без пошлины)', '776673.54', vat2)
check('№2 итог (сбор+НДС)', '795138.54', Decimal('18465') + vat2)
check('№2 статистическая стоимость USD (гр. 46)', '46428.43',
      r2(ts2 / Decimal('76.0382')))
# курс TRY: номинал 10 единиц (17,5789 за 10 TRY на 23.01.2026)
check('№2 курс TRY за единицу (17,5789 / 10)', '1.75789',
      Decimal('17.5789') / Decimal('10'))

# ---------- Эталон №3: ДТ 10702070/250326/5113751 (FOB NINGBO) ----------
goods3 = Decimal('34517.80')
cbr3 = Decimal('80.9604')
ts3 = Decimal('2911474.90')
freight3 = ts3 / cbr3 - goods3                       # восстановление фрахта из ТС
check('№3 фрахт восстановлен (USD, до центов)', '1443.92', r2(freight3))
check('№3 ТС = (товар + фрахт) x курс', '2911474.90',
      r2((goods3 + freight3) * cbr3))
duty3 = r2(ts3 * Decimal('0.03'))                    # 8483402308 — 3%
check('№3 пошлина 3%', '87344.25', duty3)
vat_base3 = ts3 + duty3
check('№3 база НДС (ТС+пошлина, гр. 5010)', '2998819.15', vat_base3)
vat3 = r2(vat_base3 * Decimal('0.22'))
check('№3 НДС 22%', '659740.21', vat3)
check('№3 сбор по шкале (скобка 2,7–4,2 млн)', '18465', scale_2026(ts3))
check('№3 итог платежей', '765549.46',
      Decimal('18465.00') + duty3 + vat3)
check('№3 статистическая стоимость USD (гр. 46)', '35961.72', r2(ts3 / cbr3))

# ---------- Отчёт ----------
fails = 0
for name, ok, expected, actual in CHECKS:
    mark = 'OK  ' if ok else 'FAIL'
    if not ok:
        fails += 1
    print(f'[{mark}] {name}: ожидалось {expected}, получено {actual}')
print(f'\nИтог: {len(CHECKS) - fails}/{len(CHECKS)} проверок сходится'
      f' (три эталонных ДТ, сверка до рубля/копейки)')
sys.exit(1 if fails else 0)
