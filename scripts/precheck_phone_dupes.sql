-- precheck_phone_dupes.sql — предпроверка дублей CustomerUser.phone (поток A волна 2, AUD-03).
-- План ред. 3 §5.1 п. 2: ОБЯЗАТЕЛЬНЫЙ шаг перед применением миграции
-- 20261108120000_bl_phone_ops на живой базе — миграция создаёт
-- уникальный индекс "CustomerUser_phone_key" ON "CustomerUser"(phone)
-- и НЕ ПРОЙДЁТ, если в данных есть дубли.
--
-- Запуск: NEON SQL Editor (или psql) ДО миграции, на той же базе, к
-- которой применяется релиз. Запрос read-only — данные не меняет.
--
-- Результат A (ожидаемый): 0 строк — дублей нет, миграцию можно применять.
-- Результат B (остановка): строки с дублями — НЕ ПРИМЕНЯТЬ миграцию,
--   разбор с владельцем (оставляем самый старый вход, остальные
--   деактивируем) и только после чистки — миграция.

-- 1) Дубли телефона пользователя компании (глобальная область, AUD-03):
--    применить миграцию можно только при 0 строк.
-- ВНИМАНИЕ (урок запуска на живой базе 2026-11-10): имена колонок в БД —
-- camelCase В КАВЫЧКАХ (Prisma без @map): "customerId", "pendingPhone".
-- snake_case (company_id) не существует — SQLSTATE 42703.
SELECT phone, count(*)::int AS cnt,
       string_agg(id || ' (' || coalesce(name, 'без имени') || ', customerId=' || "customerId" || ')', '; ') AS entries
FROM "CustomerUser"
WHERE phone IS NOT NULL
GROUP BY phone
HAVING count(*) > 1;

-- 2) Справочно: pending-заявки смены телефона (BL-8) в момент релиза.
--    Колонки появляются ТОЛЬКО ПОСЛЕ миграции bl_phone_ops — на живой
--    базе ДО миграции этот запрос вернёт ошибку о несуществующих
--    колонках: это норма, блок А (п. 1) выполняйте отдельно.
--    После релиза — контроль, что хешей кода в базе нет (код живёт
--    максимум 15 минут, открытого кода в БД не бывает):
SELECT count(*)::int AS pending_phone_changes
FROM "CustomerUser"
WHERE "pendingPhone" IS NOT NULL;
